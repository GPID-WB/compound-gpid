const crypto = require("node:crypto");
const { importDev } = require("../legacy-pages.js");
const legacy = path.join(__dirname, "fixtures/docs-redesign/legacy");
const historical = require("./fixtures/docs-redesign/legacy/scripts/rebuild-docs.js");
const sha = value => crypto.createHash("sha256").update(value).digest("hex");
function tree(root) {
  const result = {};
  function walk(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(file);
      else result[path.relative(root, file)] = sha(fs.readFileSync(file));
    }
  }
  walk(root); return result;
}
function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "cg-derivation-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const source = path.join(root, "source"), producer = path.join(root, "producer"), artifact = path.join(root, "artifact");
  const staging = path.join(root, "staging");
  fs.cpSync(path.join(__dirname, "fixtures/docs-automation/src/basic"), source, { recursive: true });
  fs.cpSync(path.join(legacy, "scripts"), path.join(source, "scripts"), { recursive: true });
  fs.writeFileSync(path.join(source, "docs/index.html"), "<html><body>Canonical home</body></html>");
  fs.cpSync(source, producer, { recursive: true });
  historical.runRebuild(producer, { all: true });
  fs.mkdirSync(artifact);
  fs.cpSync(path.join(producer, "docs"), path.join(artifact, "docs"), { recursive: true });
  fs.copyFileSync(path.join(producer, ".docs-build-metadata.json"), path.join(artifact, ".docs-build-metadata.json"));
  return { source, artifact, staging };
}

test("verified legacy import stages regenerated bytes and never mutates canonical inputs", t => {
  const f = fixture(t), before = tree(f.source);
  importDev(f.source, f.artifact, f.staging);
  assert.deepEqual(tree(f.source), before);
  assert.deepEqual(tree(path.join(f.staging, "docs")), tree(path.join(f.artifact, "docs")));
});

for (const file of ["index.html", "reference.md", "whats-new.md"]) {
  test(`self-consistent forged ${file} is rejected before promotion`, t => {
    const f = fixture(t), before = tree(f.source);
    fs.mkdirSync(f.staging); fs.writeFileSync(path.join(f.staging, "sentinel"), "valid prior output");
    const target = path.join(f.artifact, "docs", file);
    let text = fs.readFileSync(target, "utf8");
    text = file === "index.html" ? text + "forged" : text.replace("<!-- cg:auto:end -->", "forged\n<!-- cg:auto:end -->");
    fs.writeFileSync(target, text);
    const metadataPath = path.join(f.artifact, ".docs-build-metadata.json");
    const metadata = JSON.parse(fs.readFileSync(metadataPath)); metadata.site.files[file] = sha(text);
    fs.writeFileSync(metadataPath, JSON.stringify(metadata));
    assert.throws(() => importDev(f.source, f.artifact, f.staging), /canonical|generated|derivation|expected/i);
    assert.deepEqual(tree(f.source), before);
    assert.equal(fs.readFileSync(path.join(f.staging, "sentinel"), "utf8"), "valid prior output");
  });
}


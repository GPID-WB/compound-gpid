test("modern producer import and paired composition preserve sources and reject forged output end to end", t => {
  const { modernSource, modernArtifact } = require("./docs-publishing-fixture.js");
  const main = modernSource(), dev = modernSource(), artifact = modernArtifact(dev);
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "cg-pair-"));
  t.after(() => { for (const p of [main, dev, artifact, work]) fs.rmSync(p, { recursive: true, force: true }); });
  const before = [tree(main), tree(dev)];
  const staging = path.join(work, "import"), out = path.join(work, "paired");
  importDev(dev, artifact, staging);
  const composer = require("../assemble-docs-site.js");
  const options = { mainRoot: main, devRoot: dev, devBuild: staging, out, mainSha: "1".repeat(40), devSha: "2".repeat(40) };
  composer.writeCombinedSite(options);
  assert.equal(composer.verifyCombinedSite(out, main, dev, options), 0);
  assert.deepEqual([tree(main), tree(dev)], before);
  const metadata = JSON.parse(fs.readFileSync(path.join(out, "site/channels.json")));
  assert.equal(metadata.channels.development.assets.length, 8);
  assert.match(fs.readFileSync(path.join(out, "site/dev/index.html"), "utf8"), /integrity="sha256-/);
  for (const file of ["index.html", "reference.md", "reference/commands.md", "assets/command-index.json", "assets/search-index.json", "assets/site.js", "assets/docs-search.js"]) {
    const target = path.join(artifact, "docs", file), original = fs.readFileSync(target);
    fs.appendFileSync(target, "\nforged");
    const metaPath = path.join(artifact, ".docs-build-metadata.json"), originalMeta = fs.readFileSync(metaPath);
    const meta = JSON.parse(originalMeta); meta.site.files[file] = sha(fs.readFileSync(target)); fs.writeFileSync(metaPath, JSON.stringify(meta));
    assert.throws(() => importDev(dev, artifact, staging), /canonical expected output/);
    assert.deepEqual([tree(main), tree(dev)], before);
    fs.writeFileSync(target, original); fs.writeFileSync(metaPath, originalMeta);
  }
  // Self-consistent final metadata cannot turn a changed homepage into source proof.
  fs.appendFileSync(path.join(out, "site/index.html"), "forged");
  const metaPath = path.join(out, ".docs-build-metadata.json"), meta = JSON.parse(fs.readFileSync(metaPath));
  meta.site.files["index.html"] = sha(fs.readFileSync(path.join(out, "site/index.html")));
  fs.writeFileSync(metaPath, JSON.stringify(meta));
  assert.throws(() => composer.verifyCombinedSite(out, main, dev, options), /canonical expected output/);
});

test("v2 fingerprints bind absent inputs and generator/runtime code but exclude independently verified indexes", t => {
  const { modernSource } = require("./docs-publishing-fixture.js");
  const root = modernSource(); t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const fingerprint = () => require("../docs-fingerprint.js").fingerprint(root, 2);
  const original = fingerprint();
  for (const file of ["docs/assets/search-index.json", "docs/assets/command-index.json"]) fs.writeFileSync(path.join(root, file), "forged derived output");
  assert.equal(fingerprint(), original);
  const absent = path.join(root, ".github/shared/help-catalog.json"); fs.writeFileSync(absent, "{}");
  assert.notEqual(fingerprint(), original); fs.rmSync(absent);
  fs.appendFileSync(path.join(root, "scripts/docs-search-index.js"), "\n// changed generator\n");
  assert.notEqual(fingerprint(), original);
  assert.throws(() => require("../docs-provenance.js").identifyProducer(root), /code mismatch/);
  fs.writeFileSync(path.join(root, "docs/channels.json"), "{}");
  assert.throws(fingerprint, /reserved/);
});


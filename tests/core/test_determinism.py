def test_repro_passes_a_pipeline_that_writes_the_same_outputs_twice_and_records_what_it_cannot_run(env):
    """A seed above the draw, a lockfile and no path outside the project: no finding, and two runs that
    wrote the same bytes are verified. With no Run command, code still searches the change, and the record
    says that nothing was regenerated: it is inconclusive, which is no pass."""
    project = env["project"]
    (project / "pipeline.py").write_text("import random\nrandom.seed(7)\nopen('out.csv', 'w').write(str(random.random()))\n")
    (project / "uv.lock").write_text("version = 1\n")
    (project / ".cg-docs").mkdir()
    (project / ".cg-docs" / "verification.md").write_text(PROFILE.format(run=f"{PY} pipeline.py"), encoding="utf-8")
    report = begin(env)
    code, out, record, _ = repro(env, report)
    assert (code, record["verdict"], record["findings"]) == (0, "verified", []) and "output: out.csv: same\n" in out, out
    (project / ".cg-docs" / "verification.md").write_text(PROFILE.format(run="not found"), encoding="utf-8")
    (project / "pipeline.py").write_text("import random\nopen('out.csv', 'w').write(str(random.random()))\n")
    code, out, record, _ = repro(env, report)
    assert code == 1 and record["verdict"] == "inconclusive" and record["exits"] == [], out
    assert [(f["rule"], f["where"]) for f in record["findings"]] == [("unseeded", "pipeline.py:2"),
                                                                    ("no-run", ".cg-docs/verification.md")], out
    # Like a check, it runs nothing while a stop of the work waits for the human.
    assert env["cg"]("tier", *[a.replace("choice=no", "choice=yes") for a in ALL_NO], "--touches", "pipeline.py",
                     "--reads", "none", "--report", report)[0] == 0
    code, out, _, _ = repro(env, report)
    assert code == 1 and "refused: this work stops for the human's yes" in out, out



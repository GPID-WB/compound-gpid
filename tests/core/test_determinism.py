from test_work import PLAN, PY, QUICK, REPORT, fill, git, start, yes

PLANTED = HUB / "evals" / "planted" / "determinism"
CASES = json.loads((PLANTED / "expected.json").read_text(encoding="utf-8"))
BRIEF = ".cg-docs/work-reports/2026-11-27-poverty-brief.md"
PROFILE = ("---\ntype: verification-profile\nstatus: draft\n---\n\n## Run\n\n```\n{run}\n```\n\n## Outputs map\n\n"
           "| Output | Where it lives | What proves it right |\n|---|---|---|\n| A draw | `out.csv` | nothing yet |\n")


def begin(env, report="Poverty brief"):
    """Work in progress in the project: nothing committed, so every file is the change, then a work report
    and the risk of the work. The one data file is Public."""
    git(env["project"], "init", "-q")
    env["config"](data={"data/survey.csv": "Public"})
    assert env["cg"]("new", "work-report", report, "--date", "2026-11-27")[0] == 0
    name = f".cg-docs/work-reports/2026-11-27-{report.lower().replace(' ', '-')}.md"
    assert env["cg"]("tier", *ALL_NO, "--touches", "pipeline.py", "--reads", "none", "--report", name)[0] == 0
    return name


def planted(env):
    """The planted project, with its profile, which runs the pipeline with this interpreter. Its outputs were
    typed and no commit holds them, so the human's yes to writing over them is on record (stop rule 1, #230)."""
    project = env["project"]
    shutil.copytree(PLANTED / "project", project, dirs_exist_ok=True)
    (project / ".cg-docs").mkdir(exist_ok=True)
    profile = (PLANTED / "verification.md").read_text(encoding="utf-8").replace("\npython ", f"\n{PY} ")
    (project / ".cg-docs" / "verification.md").write_text(profile, encoding="utf-8")
    overwrite(env, begin(env))
    return project


def overwrite(env, report):
    """The overwrite declared as stop rule 1 of the work playbook says, and the human's plain yes to it."""
    assert env["cg"]("tier", *yes("irreversible"), "--touches", "pipeline.py", "--reads", "none", "--report", report)[0] == 0
    fill(env["project"] / report)
    assert env["cg"]("approve", report, "--reply", "Yes.")[0] == 0


def repro(env, report=BRIEF):
    """What repro printed, its exit code, and the newest record it wrote, with its path."""
    code, out = env["cg"]("repro", "--report", report)
    found = sorted((env["project"] / ".cg-docs" / "evidence" / report.split("/")[-1][:-3]).glob("*-repro.json"))
    record = json.loads(found[-1].read_text(encoding="utf-8")) if found else {}
    return code, out, record, found[-1].relative_to(env["project"]).as_posix() if found else ""


def where(project, case):
    """Where a planted case shows: the path, and the line that holds its text when it has one."""
    if "text" not in case:
        return case["file"], 0
    lines = (project / case["file"]).read_text(encoding="utf-8").splitlines()
    return case["file"], next(n for n, line in enumerate(lines, 1) if case["text"] in line)


def at(spot, case_at):
    """True when the place of a finding is where a case shows: the same path, and a line or a range that
    holds the case's line."""
    name, _, lines = spot.partition(":")
    first, _, last = lines.partition("-")
    return name == case_at[0] and (not case_at[1] or bool(first) and int(first) <= case_at[1] <= int(last or first))


